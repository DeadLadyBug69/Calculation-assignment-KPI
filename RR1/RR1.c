#include <stdio.h>
#include <windows.h>

int main() {
    // Ініціалізація консолі для конкретного відображення укр. мови
    SetConsoleOutputCP(CP_UTF8);
    
    // Оголошення дробового та цілочисельного типу даних
    // Та ініціалізація їх змінних
    double a;
    int N;
    
    printf("Введіть значення a: ");
    scanf("%lf", &a);
    
    // Захист від некоректного вводу
    // N не може бути від'ємним
    do {
        printf("Введіть значення N (N >= 0): ");
        scanf("%d", &N);
    } while (N < 0);
    
    // Ініціалізація змінної для накопичення суми
    double S = 0.0;
    
    // Для n = 0, a^0 / 0! = 1
    double current = 1.0; 
    
    for (int n = 0; n <= N; n++) {
        if (n > 0) {
            // Формула:
            // a^2n / (2n)! = (a^2n-2 / (2n-2)!) * (a^2) / ((2n-1)*2n)
            current = current * (-1) * (a * a) / ((2.0 * n - 1) * (2.0 * n));
        }
        
        S += current;
    }
    
    // Виведення результату 
    printf("Сума ряду S = %lf\n", S);
    
    return 0;
}
